def extract_state_dict(
    checkpoint
):

    """
    Support either:

        state_dict

    or:

        model_state_dict

    or a raw state dictionary.
    """

    if isinstance(
        checkpoint,
        dict
    ):

        if (
            "model_state_dict"
            in checkpoint
        ):

            return checkpoint[
                "model_state_dict"
            ]

        if (
            "state_dict"
            in checkpoint
        ):

            return checkpoint[
                "state_dict"
            ]

    return checkpoint


