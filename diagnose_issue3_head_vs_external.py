# =====================================================================
# CANONICAL SMILES
# =====================================================================

def canonical_smiles(
    mol
):

    if mol is None:

        return None

    try:

        Chem.SanitizeMol(
            mol
        )

        return Chem.MolToSmiles(
            mol,
            canonical=True,
        )

    except Exception:

        return None


# =====================================================================
# CLEAN SMILES
# =====================================================================

def clean_smiles(
    smiles
):

    if smiles is None:

        return None

    # ---------------------------------------------------------------
    # Keep largest connected component.
    # ---------------------------------------------------------------

    if "." in smiles:

        fragments = (
            smiles.split(".")
        )

        smiles = max(
            fragments,
            key=len,
        )

        mol = Chem.MolFromSmiles(
            smiles
        )

        if mol is None:

            return None

        smiles = canonical_smiles(
            mol
        )

    # ---------------------------------------------------------------
    # Replace wildcard atoms if present.
    # ---------------------------------------------------------------

    if (
        smiles is not None
        and "*" in smiles
    ):

        smiles = smiles.replace(
            "*",
            "C",
        )

        mol = Chem.MolFromSmiles(
            smiles
        )

        if mol is None:

            return None

        smiles = canonical_smiles(
            mol
        )

    return smiles


# =====================================================================
# DECODE GENERATED GRAPHS
# =====================================================================

def decode_graphs(
    dataset,
    generated_nodes,
    generated_edges,
):

    smiles_list = []

    decoder_failures = 0

    for (
        edge_graph,
        node_graph,
    ) in zip(
        generated_edges,
        generated_nodes,
    ):

        try:

            mol = dataset.matrices2mol(

                node_graph.detach()
                .cpu()
                .numpy(),

                edge_graph.detach()
                .cpu()
                .numpy(),

                strict=False,
            )

            smiles = canonical_smiles(
                mol
            )

            smiles = clean_smiles(
                smiles
            )

            smiles_list.append(
                smiles
            )

        except Exception as exc:

            decoder_failures += 1

            print(
                "Decoder warning: "
                f"{type(exc).__name__}: "
                f"{exc}"
            )

            smiles_list.append(
                None
            )

    return (
        smiles_list,
        decoder_failures,
    )


# =====================================================================
# MORGAN FINGERPRINTS
# =====================================================================

def smiles_to_morgan(
    smiles_list
):

    fingerprints = []

    valid_smiles = []

    for smiles in smiles_list:

        if smiles is None:

            continue

        mol = Chem.MolFromSmiles(
            smiles
        )

        if mol is None:

            continue

        fp = (
            AllChem
            .GetMorganFingerprintAsBitVect(
                mol,
                radius=2,
                nBits=2048,
            )
        )

        fingerprints.append(

            np.asarray(
                fp,
                dtype=np.float32,
            )
        )

        valid_smiles.append(
            smiles
        )

    return (
        valid_smiles,
        fingerprints,
    )


# =====================================================================
# RUN ONE CONDITION
# =====================================================================

@torch.no_grad()
def run_condition(

    generator,

    discriminator,

    external_model,

    dataset,

    fixed_batches,

    requested_pic50,

    requested_logbb,

    nodes,

    edges,
):

    # =================================================================
    # NORMALIZE CONDITION
    # =================================================================

    normalized_condition = torch.tensor(

        [

            # BACE1 target condition
            1.0,

            # normalized pIC50
            (
                requested_pic50
                - PIC50_MEAN
            )
            / PIC50_STD,

            # normalized logBB
            (
                requested_logbb
                - BBB_MEAN
            )
            / BBB_STD,

        ],

        dtype=torch.float32,

        device=DEVICE,
    )

    # =================================================================
    # STORAGE
    # =================================================================

    all_smiles = []

    all_head_predictions = []

    total_generated = 0

    total_decoder_failures = 0

    # =================================================================
    # GENERATE
    # =================================================================

    for mol_batch in fixed_batches:

        batch_size = (
            mol_batch.num_graphs
        )

        total_generated += (
            batch_size
        )

        # -------------------------------------------------------------
        # Convert PyG batch into DrugGEN tensors.
        # -------------------------------------------------------------

        (
            _,
            a_tensor,
            x_tensor,
        ) = load_molecules(

            data=mol_batch,

            batch_size=batch_size,

            device=DEVICE,

            b_dim=edges,

            m_dim=nodes,
        )

        # -------------------------------------------------------------
        # Repeat requested condition for batch.
        # -------------------------------------------------------------

        condition = (

            normalized_condition

            .unsqueeze(0)

            .repeat(
                batch_size,
                1,
            )
        )

        # -------------------------------------------------------------
        # Generator.
        #
        # Returns:
        #
        # z_e
        # z_n
        # node_logits
        # edge_logits
        # -------------------------------------------------------------

        (
            z_e,
            z_n,
            node_logits,
            edge_logits,
        ) = generator(

            a_tensor,

            x_tensor,

            condition,
        )

        # -------------------------------------------------------------
        # We intentionally DO NOT use z_e/z_n for the property head.
        #
        # z_n = [B,45,128]
        # z_e = [B,45,45,128]
        #
        # The property head expects graph features of dimensions:
        #
        # nodes = 14
        # edges = 5
        # -------------------------------------------------------------

        # =================================================================
        # DISCRETE GRAPH FOR MOLECULE DECODING
        # =================================================================

        generated_nodes = torch.argmax(

            node_logits,

            dim=-1,
        )

        generated_edges = torch.argmax(

            edge_logits,

            dim=-1,
        )

        (
            batch_smiles,
            decoder_failures,
        ) = decode_graphs(

            dataset,

            generated_nodes,

            generated_edges,
        )

        total_decoder_failures += (
            decoder_failures
        )

        # =================================================================
        # RELAXED GRAPH FOR ISSUE 3 PROPERTY HEAD
        # =================================================================

        """
        IMPORTANT:

        Your current relax_graph() implementation returns:

            relaxed_edges
            relaxed_nodes

        NOT:

            relaxed_nodes
            relaxed_edges

        Therefore the assignment below intentionally uses:

            relaxed_edges, relaxed_nodes
        """

        (
            relaxed_edges,
            relaxed_nodes,
        ) = relax_graph(

            node_logits,

            edge_logits,

            mode="st",
        )

        # =================================================================
        # SHAPE CHECKS
        # =================================================================

        print(
            "Relaxed graph shapes: "
            f"edges={tuple(relaxed_edges.shape)}, "
            f"nodes={tuple(relaxed_nodes.shape)}"
        )

        if (
            relaxed_nodes.shape[-1]
            != nodes
        ):

            raise RuntimeError(

                "Unexpected node feature "
                "dimension.\n"

                f"Received: "
                f"{relaxed_nodes.shape}\n"

                f"Expected final dimension: "
                f"{nodes}"
            )

        if (
            relaxed_edges.shape[-1]
            != edges
        ):

            raise RuntimeError(

                "Unexpected edge feature "
                "dimension.\n"

                f"Received: "
                f"{relaxed_edges.shape}\n"

                f"Expected final dimension: "
                f"{edges}"
            )

        # =================================================================
        # ISSUE 3 PROPERTY HEAD
        # =================================================================

        property_prediction = (

            discriminator.predict_properties(

                relaxed_edges,

                relaxed_nodes,

            )

            .detach()

            .cpu()

            .numpy()
        )

        # =================================================================
        # STORE VALID MOLECULES
        # =================================================================

        for (
            smiles,
            prediction,
        ) in zip(

            batch_smiles,

            property_prediction,
        ):

            if smiles is None:

                continue

            all_smiles.append(
                smiles
            )

            # ---------------------------------------------------------
            # Convert normalized predictions back to physical units.
            # ---------------------------------------------------------

            predicted_pic50 = (

                prediction[0]

                * PIC50_STD

                + PIC50_MEAN
            )

            predicted_logbb = (

                prediction[1]

                * BBB_STD

                + BBB_MEAN
            )

            all_head_predictions.append(

                [
                    predicted_pic50,

                    predicted_logbb,
                ]
            )

    # =================================================================
    # INDEPENDENT BACE1 PREDICTOR
    # =================================================================

    (
        external_valid_smiles,
        fingerprints,
    ) = smiles_to_morgan(
        all_smiles
    )

    if len(fingerprints) > 0:

        external_predictions = (

            external_model.predict(

                np.asarray(

                    fingerprints,

                    dtype=np.float32,
                )
            )
        )

    else:

        external_predictions = (
            np.asarray(
                [],
                dtype=np.float64,
            )
        )

    # =================================================================
    # PROPERTY HEAD ARRAY
    # =================================================================

    head = np.asarray(

        all_head_predictions,

        dtype=np.float64,
    )

    # =================================================================
    # RETURN
    # =================================================================

    return {

        "requested_pIC50":
            requested_pic50,

        "requested_logBB":
            requested_logbb,

        "total_generated":
            total_generated,

        "valid":
            len(all_smiles),

        "unique":
            len(set(all_smiles)),

        "decoder_failures":
            total_decoder_failures,

        "property_head_predictions":
            len(head),

        "external_predictions":
            len(external_predictions),

        # -------------------------------------------------------------
        # Issue 3 property head
        # -------------------------------------------------------------

        "head_pIC50_mean":

            (
                float(
                    head[:, 0].mean()
                )

                if len(head)

                else np.nan
            ),

        "head_pIC50_median":

            (
                float(
                    np.median(
                        head[:, 0]
                    )
                )

                if len(head)

                else np.nan
            ),

        "head_pIC50_max":

            (
                float(
                    head[:, 0].max()
                )

                if len(head)

                else np.nan
            ),

        "head_logBB_mean":

            (
                float(
                    head[:, 1].mean()
                )

                if len(head)

                else np.nan
            ),

        "head_logBB_median":

            (
                float(
                    np.median(
                        head[:, 1]
                    )
                )

                if len(head)

                else np.nan
            ),

        "head_logBB_max":

            (
                float(
                    head[:, 1].max()
                )

                if len(head)

                else np.nan
            ),

        # -------------------------------------------------------------
        # Independent BACE1 predictor
        # -------------------------------------------------------------

        "external_pIC50_mean":

            (
                float(
                    np.mean(
                        external_predictions
                    )
                )

                if len(
                    external_predictions
                )

                else np.nan
            ),

        "external_pIC50_median":

            (
                float(
                    np.median(
                        external_predictions
                    )
                )

                if len(
                    external_predictions
                )

                else np.nan
            ),

        "external_pIC50_max":

            (
                float(
                    np.max(
                        external_predictions
                    )
                )

                if len(
                    external_predictions
                )

                else np.nan
            ),
    }


