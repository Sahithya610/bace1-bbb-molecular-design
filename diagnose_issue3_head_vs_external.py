
"""
Issue 3 diagnostic: property head vs independent BACE1 predictor.

Purpose
-------
Determine whether the continuous BACE1 pIC50 condition actually changes
the chemistry generated by the Issue 3 conditional DrugGEN model.

Requested conditions:

    pIC50 = 5.5
    pIC50 = 6.5
    pIC50 = 7.0
    pIC50 = 8.0
    pIC50 = 9.0

For every condition:

1. The exact same fixed ChEMBL input graphs are used.
2. Only the requested pIC50 condition is changed.
3. The generated molecules are decoded.
4. The Issue 3 auxiliary property head predicts pIC50/logBB.
5. The independent BACE1 ExtraTrees model predicts pIC50.
6. Results are compared across conditions.

IMPORTANT TENSOR INFORMATION
----------------------------

ConditionalGenerator returns:

    z_e
        [B, 45, 45, 128]

    z_n
        [B, 45, 128]

    node_logits
        [B, 45, 14]

    edge_logits
        [B, 45, 45, 5]

The discriminator property path expects graph features:

    node features = 14
    edge features = 5

Therefore z_e and z_n must NOT be passed to predict_properties().

The current relax_graph() implementation returns:

    relaxed_edges
    relaxed_nodes

in that order.

Therefore:

    relaxed_edges, relaxed_nodes = relax_graph(...)

Then:

    discriminator.predict_properties(
        relaxed_edges,
        relaxed_nodes
    )

No retraining is performed.
No model weights are modified.
"""


