def load_generator(
    vertexes,
    nodes,
    edges,
):

    model = ConditionalGenerator(

        act="relu",

        vertexes=vertexes,

        edges=edges,

        nodes=nodes,

        dropout=DROPOUT,

        dim=DIM,

        depth=DEPTH,

        heads=HEADS,

        mlp_ratio=MLP_RATIO,
    ).to(DEVICE)

    checkpoint = torch.load(

        GENERATOR_CHECKPOINT,

        map_location=DEVICE,

        weights_only=False,
    )

    model.load_state_dict(

        extract_state_dict(
            checkpoint
        )
    )

    model.eval()

    return model


