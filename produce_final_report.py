"""
Final ranked report combining oracle pIC50 + Vina docking scores.
Produces:
  results/docking/bace1_final_ranked.csv   — full table
  results/docking/bace1_top10_report.txt   — human-readable top-10
"""
import pandas as pd
import numpy as np
import os

os.chdir(os.path.dirname(os.path.abspath(__file__)))

df = pd.read_csv("results/docking/bace1_druggen_top_vina.csv")
docked = df[df["vina_score"].notna()].copy()

# ── Composite score ───────────────────────────────────────────────
# Normalise both scores to [0,1] and combine:
#   oracle: higher = better → normalise as (x - min)/(max - min)
#   vina:   lower  = better → normalise as (max - x)/(max - min)
o_min, o_max = docked["oracle_pIC50"].min(), docked["oracle_pIC50"].max()
v_min, v_max = docked["vina_score"].min(),   docked["vina_score"].max()

docked["oracle_norm"] = (docked["oracle_pIC50"] - o_min) / (o_max - o_min)
docked["vina_norm"]   = (v_max - docked["vina_score"])  / (v_max - v_min)
# Equal-weight composite
docked["composite"] = 0.5 * docked["oracle_norm"] + 0.5 * docked["vina_norm"]

docked = docked.sort_values("composite", ascending=False).reset_index(drop=True)
docked["final_rank"] = range(1, len(docked)+1)

# Add BBB flag
docked["BBB_positive"] = docked["predicted_logBB"] >= 0.0

# Save full table
OUT_CSV = "results/docking/bace1_final_ranked.csv"
docked.to_csv(OUT_CSV, index=False)

# ── Print report ─────────────────────────────────────────────────
SEP = "="*72
print(SEP)
print("BACE1 DrugGEN CANDIDATE REPORT")
print("Final ranking: 50% oracle pIC50 + 50% Vina docking score")
print(SEP)
print(f"\nTotal docked: {len(docked)}/50")
print(f"BBB-positive (logBB≥0): {docked['BBB_positive'].sum()} ({100*docked['BBB_positive'].mean():.0f}%)")
print(f"\nVina score range: {docked['vina_score'].min():.2f} to {docked['vina_score'].max():.2f} kcal/mol")
print(f"Oracle pIC50 range: {docked['oracle_pIC50'].min():.3f} to {docked['oracle_pIC50'].max():.3f}")

print(f"\n{'─'*72}")
print("TOP 10 CANDIDATES (composite score)")
print(f"{'─'*72}")
for _, r in docked.head(10).iterrows():
    bbb = "BBB+" if r["BBB_positive"] else "BBB-"
    print(f"\n  Rank {int(r['final_rank'])}  |  Composite: {r['composite']:.3f}  |  {bbb}")
    print(f"  Oracle pIC50:  {r['oracle_pIC50']:.3f}")
    print(f"  Vina score:    {r['vina_score']:.2f} kcal/mol")
    print(f"  logBB:         {r['predicted_logBB']:+.3f}")
    print(f"  MW: {r['MW']:.0f}  LogP: {r['LogP']:.2f}  TPSA: {r['TPSA']:.0f}  HBD: {int(r['HBD'])}")
    print(f"  SMILES: {r['canonical_smiles']}")

# Write text report
TXT = "results/docking/bace1_top10_report.txt"
import sys
lines = []
